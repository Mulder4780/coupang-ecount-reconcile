def check(grade="", type_="", reason=""):
    """저장 전에 값이 성립하는지 본다. 어긋나면 사람이 읽는 말로 알려 준다.

    돌려주는 것은 `(ok, 안 되는 이유)` 이고, 되면 이유가 빈 문자열이다.
    ★ 막기만 하는 안내는 없는 안내다([408]) — 무엇을 고르면 되는지 같이 적는다.
    """
    grade = str(grade or "").strip()
    type_ = str(type_ or "").strip()
    reason = str(reason or "").strip()

    if not grade or grade == GRADE_UNSET:
        # 아직 안 정한 것은 정상이다 — 유형·사유를 강요하지 않는다.
        if type_:
            return False, ("등급을 먼저 고르세요 — 유형만 있고 등급이 없으면 "
                           "이 건이 A인지 B인지 알 수 없습니다")
        return True, ""

    if grade not in GRADES:
        return False, ("대응등급은 " + " · ".join(GRADES) + " 중 하나여야 합니다"
                       " (아직 못 정했으면 비워 두세요 — " + GRADE_UNSET + "로 남습니다)")

    if type_ and type_ not in TYPES[grade]:
        return False, (grade + " 의 유형은 " + " · ".join(TYPES[grade])
                       + " 중 하나여야 합니다 (지금 값: " + type_ + ")")

    if grade in GRADE_NEEDS_REASON and not reason:
        return False, ("즉시 출동은 **왜 즉시인지** 사유를 적어야 합니다 — "
                       "대표 보고에 그 근거가 그대로 실립니다")

    return True, ""


def meta():
    """화면이 읽는 표 한 장. 화면이 낱말을 제 손으로 적지 않게 한다([162])."""
    return {
        "등급": list(GRADES),
        "미분류": GRADE_UNSET,
        "등급설명": dict(GRADE_NOTE),
        "유형": {g: list(TYPES[g]) for g in GRADES},
        "유형설명": dict(TYPE_NOTE),
        "사유필수": list(GRADE_NEEDS_REASON),
        "권역": list(REGIONS),
        # 증상→등급 표는 아직 없다. 화면이 "자동으로 매겨진다"고 오해하지 않게
        # 그 사실을 그대로 싣는다([169]).
        # 추천은 **확정이 아니다**.  화면이 그 사실을 그대로 말해야 사람이
        # "앱이 정해 줬다"고 오해하지 않는다([169]).
        "자동판정": False,
        "추천있음": True,
        "추천표": (RULES_FILE if load_rules()[1] else "기본표(as_grade.py)"),
        "안내": ("등급은 사람이 고릅니다. 증상 글에서 뽑은 **추천**을 같이 보여 주지만 "
                 "저장되는 값은 사람이 고른 것뿐입니다."),
    }


