def region_of(camp_name="", address=""):
    """캠프명·주소에서 권역을 고른다. 못 가르면 `미분류`([169]).

    ★ **후보가 유일할 때만** 답한다([172]) — 두 권역 낱말이 같이 잡히면 모른다고
      말한다. 예: 주소에 '경기'와 '광주'가 같이 있으면 광주광역시인지 경기 광주시인지
      원본이 말해 주지 않는다. 잘못 묶으면 기사가 엉뚱한 곳으로 간다.
    ★ **주소가 먼저다** — 캠프명은 사람이 손으로 적어 표기가 흔들린다.
    """
    for text in (str(address or ""), str(camp_name or "")):
        text = text.strip()
        if not text:
            continue
        hit = {r for r, words in _REGION_WORDS.items() if any(w in text for w in words)}
        if len(hit) == 1:
            return hit.pop()
        if len(hit) > 1:
            return GRADE_UNSET          # 갈리면 모른다 — 지어내지 않는다
    return GRADE_UNSET


