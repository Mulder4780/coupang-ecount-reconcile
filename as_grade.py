_CRASH_WORDS = ("충돌", "충격", "부딪", "추돌", "들이받", "들이박", "박음", "박아")
_CRASH_NOT = ("충돌방지",)          # 부품 이름 — 차가 부딪친 것이 아니다


def car_crash(text=""):
    """차량이 부딪친 것으로 보이나 — 짝일 때만 답한다([172]).

    돌려주는 것: 걸린 낱말 짝(`차량+충돌`) 또는 빈 글자.
    """
    s = str(text or "")
    if not s:
        return ""
    for bad in _CRASH_NOT:
        s = s.replace(bad, "")     # 부품 이름을 먼저 지운다
    car = next((w for w in _CAR_WORDS if w in s), "")
    if not car:
        return ""
    hit = next((w for w in _CRASH_WORDS if w in s), "")
    return (car + "+" + hit) if hit else ""


